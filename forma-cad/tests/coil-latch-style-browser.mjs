import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {chromium} from 'playwright';
import {defaults} from '../src/geometry.js';

const browser=await chromium.launch({channel:'msedge',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1700,height:1200},acceptDownloads:true}),errors=[];
 page.setDefaultTimeout(120000);
 page.on('pageerror',error=>errors.push(error.message));page.on('dialog',dialog=>dialog.accept(dialog.defaultValue()));
 await page.addInitScript(()=>window.showSaveFilePicker=undefined);
 await page.goto('http://127.0.0.1:5188');
 const original={format:'forma-cad',version:1,features:[{...defaults,id:'body',name:'円柱',kind:'extrusion',profile:'circle',diameter:60,depth:80}]};
 await page.locator('#file').setInputFiles({name:'ridge-ui.forma.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(original))});
 await page.locator('#project-preview-open').click();
 await page.waitForFunction(()=>document.getElementById('body-count').textContent==='1');
 await page.locator('#direct-coil-joint').evaluate(element=>element.click());
 assert.equal(await page.locator('#cad-latchStyle').inputValue(),'ridge');
 assert.equal(Number(await page.locator('#cad-latchGap').inputValue()),.05);
 assert.equal(await page.locator('#cad-latchFirm').isHidden(),true);
 await page.waitForFunction(()=>document.getElementById('canvas-host').dataset.machiningPreview==='coilJoint',{},{timeout:180000});
 await fs.mkdir('generated',{recursive:true});
 await page.screenshot({path:'generated/coil-ridge-preview.png'});
 await page.locator('#cad-apply').click();
 await page.waitForFunction(()=>!document.getElementById('tools-dialog').open,{},{timeout:600000});
 const download=page.waitForEvent('download');
 await page.locator('#save').click();
 const saved=JSON.parse(await fs.readFile(await(await download).path(),'utf8'));
 const joint=saved.features.find(feature=>feature.spec?.type==='coilJoint');
 assert.ok(joint);
 assert.equal(joint.spec.latchStyle,'ridge');
 assert.equal(joint.analysis.latchStyle,'ridge');
 assert.equal(joint.outputs.length,2);
 await page.locator('#file').setInputFiles({name:'ridge-saved.forma.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(saved))});
 await page.locator('#project-preview-open').click();
 await page.waitForFunction(()=>document.getElementById('file').value==='');
 await page.locator('#features .tree-row').last().locator('button.row-label').click();
 assert.equal(await page.locator('#cad-latchStyle').inputValue(),'ridge');
 assert.equal(Number(await page.locator('#cad-latchGap').inputValue()),.05);
 assert.equal(await page.locator('#cad-latchFirm').isHidden(),true);
 await page.locator('#cad-latchStyle').selectOption('claw');
 assert.equal(Number(await page.locator('#cad-latchGap').inputValue()),.15);
 assert.equal(await page.locator('#cad-latchFirm').isHidden(),false);
 await page.locator('#cad-latchStyle').selectOption('ridge');
 assert.equal(Number(await page.locator('#cad-latchGap').inputValue()),.05);
 assert.equal(await page.locator('#cad-latchFirm').isHidden(),true);
 await page.locator('#cad-cancel').click();
 assert.deepEqual(errors,[]);
 console.log('PASS ridge preview/apply/save/edit and claw switch');
}finally{await browser.close();}
