import {chromium} from 'playwright';
import * as THREE from 'three';
import * as R from 'replicad';
import init from '../node_modules/replicad-opencascadejs/dist/replicad_single.js';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {defaults} from '../src/geometry.js';
import {runOperation} from '../src/kernel.js';

R.setOC(await init({wasmBinary:await fs.readFile('node_modules/replicad-opencascadejs/dist/replicad_single.wasm')}));
const source={...defaults,id:'source',name:'対象',width:30,height:20,depth:20};
const spec={type:'enclose',id:'hinge',target:'source',thickness:2,clearance:.5,boxMode:true,faces:[],enclosureSplit:'XY',splitOffset:10,hinge:true,hingeEdge:'+Y',hingeRadialGap:.5,hingeAxialGap:.5,hingeAngle:0};
const operation=runOperation([source],spec);
const pivot=operation.analysis.hingeFrame.point;
const browser=await chromium.launch({channel:'msedge',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1800,height:1100}}),errors=[];
 page.setDefaultTimeout(120000);
 page.on('pageerror',error=>errors.push(error.message));
 page.on('dialog',dialog=>dialog.accept(dialog.defaultValue()));
 await page.goto('http://127.0.0.1:5188');
 await page.locator('#file').setInputFiles({name:'hinge-box.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({format:'forma-cad',version:1,features:[source,{kind:'cadop',id:'enc',name:'囲み',spec,...operation}]}))});
 await page.waitForFunction(()=>document.getElementById('body-count').textContent==='3');
 const host=page.locator('#canvas-host');
 const camera=async()=>JSON.parse(await host.getAttribute('data-camera-state'));
 const preview=async()=>JSON.parse(await host.getAttribute('data-move-preview'));
 const project=async world=>{
  const rect=await page.locator('canvas').boundingBox(),state=await camera();
  const camera3d=new THREE.OrthographicCamera(-100*rect.width/rect.height,100*rect.width/rect.height,100,-100,.1,100000);
  camera3d.position.fromArray(state);camera3d.quaternion.fromArray(state,3);camera3d.zoom=state[7];camera3d.updateProjectionMatrix();camera3d.updateMatrixWorld(true);
  const p=new THREE.Vector3(...world).project(camera3d);
  return {x:rect.x+(p.x+1)*rect.width/2,y:rect.y+(1-p.y)*rect.height/2};
 };
 await page.locator('[data-view=top]').click();await page.locator('#fit').click();
 await page.locator('#move-tool').click();
 const lid=await project([0,0,22.5]);await page.mouse.click(lid.x,lid.y);
 assert.ok((await preview()).edgeAxis,'hinged lid should auto select its physical axis');
 await page.locator('[data-view=right]').click();
 const center=await project(pivot),rect=await page.locator('canvas').boundingBox(),radius=rect.height*.1;
 await page.mouse.move(center.x+radius,center.y);await page.mouse.down();
 await page.mouse.move(center.x+radius*Math.cos(Math.PI/6),center.y+radius*Math.sin(Math.PI/6),{steps:6});
 const before=await camera(),angle=Number(await page.locator('#move-edge-angle').inputValue()),pose=await preview();
 assert.ok(Math.abs(angle)>5,'lid hinge drag should be active');
 await page.mouse.wheel(0,-180);await page.waitForTimeout(100);
 const zoomed=await camera();
 assert.ok(zoomed[7]>before[7]*1.01,'plain wheel zooms in during the lid drag');
 assert.ok(zoomed.slice(0,7).every((n,i)=>Math.abs(n-before[i])<1e-6),'zoom must not orbit or pan the camera');
 assert.deepEqual(await preview(),pose,'zoom must preserve the lid pose during drag');
 assert.ok(Math.abs(Number(await page.locator('#move-edge-angle').inputValue())-angle)<.001,'zoom must preserve the lid angle');
 await page.mouse.move(center.x+radius*Math.cos(Math.PI/6)+2,center.y+radius*Math.sin(Math.PI/6)+2);
 const resumedAngle=Number(await page.locator('#move-edge-angle').inputValue());
 assert.ok(Math.abs(resumedAngle-angle)<12,'small pointer movement after zoom must not jump the hinge angle');
 await page.mouse.up();
 const beforeOrbit=await camera(),beforeOrbitPose=await preview();
 await page.keyboard.down('Shift');await page.mouse.wheel(0,120);await page.keyboard.up('Shift');
 await page.waitForTimeout(100);
 const orbited=await camera();
 assert.equal(orbited[7],beforeOrbit[7],'Shift + wheel keeps zoom fixed');
 assert.ok(orbited.slice(0,7).some((n,i)=>Math.abs(n-beforeOrbit[i])>1e-6),'Shift + wheel still orbits the view');
 assert.deepEqual(await preview(),beforeOrbitPose,'orbit keeps the lid pose fixed');
 const beforeZoomOut=await camera(),beforeZoomOutPose=await preview();
 await page.mouse.wheel(0,180);await page.waitForTimeout(100);
 const zoomedOut=await camera();
 assert.ok(zoomedOut[7]<beforeZoomOut[7]*.99,'plain wheel also zooms after releasing the drag');
 assert.deepEqual(await preview(),beforeZoomOutPose,'zoom after release preserves the lid pose');
 assert.deepEqual(errors,[]);
 console.log('PASS plain wheel zooms during and after lid hinge drag; Shift + wheel orbits without zooming; lid pose remains fixed');
}finally{await browser.close();}
