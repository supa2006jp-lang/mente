import {chromium} from 'playwright';
import {defaults,validateProject} from '../src/geometry.js';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';

const browser=await chromium.launch({channel:'msedge',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1700,height:1200},acceptDownloads:true}),errors=[];
 page.setDefaultTimeout(120000);
 page.on('pageerror',error=>errors.push(error.message));
 page.on('dialog',dialog=>dialog.accept(dialog.defaultValue()));
 await page.addInitScript(()=>Object.defineProperty(window,'showSaveFilePicker',{value:undefined,configurable:true}));
 await page.goto('http://127.0.0.1:5188');
 const features=[{...defaults,id:'box',name:'対象',width:30,height:20,depth:20,x:0,y:0}];
 await page.locator('#file').setInputFiles({name:'box.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({format:'forma-cad',version:1,features}))});
 await page.waitForFunction(()=>document.getElementById('body-count').textContent==='1');
 await page.locator('#direct-enclose').evaluate(element=>element.click());
 await page.locator('#cad-boxMode').check();
 await page.locator('#cad-hinge').check();
 assert.equal(await page.locator('#cad-autoExpandMotion').isChecked(),false);
 assert.equal(await page.locator('#cad-snapLatch').isChecked(),false);
 await page.locator('#cad-hingeEdge').selectOption('+Y');
 await page.locator('#cad-autoExpandMotion').check();
 await page.locator('#cad-motionGap').fill('0.7');
 await page.locator('#cad-snapLatch').check();
 await page.locator('#cad-latchGap').fill('0.45');
 await page.locator('#cad-seamGap').fill('0.4');
 await page.locator('#cad-latchEngagement').fill('0.25');
 assert.equal(await page.locator('#enclose-motion-gap').isVisible(),true);
 assert.equal(await page.locator('#enclose-latch-gap').isVisible(),true);
 assert.equal(await page.locator('#enclose-latch-engagement').isVisible(),true);
 await page.waitForFunction(()=>document.getElementById('enclose-motion-result')?.textContent.includes('0〜90°を確認'),{},{timeout:120000});
 assert.match(await page.locator('#enclose-motion-result').textContent(),/BOXを各方向に/);
 assert.match(await page.locator('#enclose-motion-result').textContent(),/爪の開閉検査/);
 await page.locator('#cad-apply').click();
 await page.waitForFunction(()=>!document.getElementById('tools-dialog').open,{},{timeout:120000});
 assert.equal(await page.locator('#body-count').textContent(),'3');
 const saved=page.waitForEvent('download');await page.locator('#save').click();
 const data=JSON.parse(await fs.readFile(await(await saved).path(),'utf8'));validateProject(data);
 let operation=data.features.at(-1);
 assert.equal(operation.spec.autoExpandMotion,true);
 assert.equal(operation.spec.snapLatch,true);
 assert.equal(operation.spec.motionGap,0.7);
 assert.equal(operation.spec.latchGap,0.45);
 assert.equal(operation.spec.hardwareScale,1.3);
 assert.equal(operation.spec.latchProfile,'triangle');
 assert.equal(operation.spec.seamGap,0.4);
 assert.equal(operation.spec.latchEngagement,0.25);
 assert.ok(operation.analysis?.boxExtra>0,'motion sweep expands the tight BOX');
 assert.ok(operation.analysis.minSampleGap>=0.7,'measured motion gap meets the request');
 assert.equal(operation.outputs.length,2);
 const firstExtra=operation.analysis.boxExtra;
 await page.locator('#features .tree-row').last().locator('button.row-label').click();
 assert.equal(await page.locator('#cad-autoExpandMotion').isChecked(),true);
 assert.equal(await page.locator('#cad-snapLatch').isChecked(),true);
 assert.equal(await page.locator('#cad-motionGap').inputValue(),'0.7');
 assert.equal(await page.locator('#cad-latchGap').inputValue(),'0.45');
 assert.equal(await page.locator('#cad-seamGap').inputValue(),'0.4');
 assert.equal(await page.locator('#cad-latchEngagement').inputValue(),'0.25');
 await page.locator('#cad-motionGap').fill('0.8');
 await page.locator('#cad-latchGap').fill('0.5');
 await page.locator('#cad-seamGap').fill('0.5');
 await page.locator('#cad-latchEngagement').fill('0.2');
 await page.locator('#cad-apply').click();
 await page.waitForFunction(()=>!document.getElementById('tools-dialog').open,{},{timeout:120000});
 assert.equal(await page.locator('#body-count').textContent(),'3');
 const editedSave=page.waitForEvent('download');await page.locator('#save').click();
 const edited=JSON.parse(await fs.readFile(await(await editedSave).path(),'utf8'));validateProject(edited);
 operation=edited.features.at(-1);
 assert.equal(operation.spec.motionGap,0.8);
 assert.equal(operation.spec.latchGap,0.5);
 assert.equal(operation.spec.seamGap,0.5);
 assert.equal(operation.spec.latchEngagement,0.2);
 assert.ok(operation.analysis?.boxExtra>=firstExtra,'a larger requested gap does not shrink the BOX');
 const exported=page.waitForEvent('download');await page.locator('#export-enclosure').click();
 const bytes=await fs.readFile(await(await exported).path());
 await page.waitForFunction(()=>document.getElementById('toast').textContent.includes('姿勢をCAD形状で検証しました'));
 const count=bytes.readUInt32LE(80);
 assert.equal(bytes.length,84+count*50);
 assert.equal(count,operation.outputs.reduce((sum,output)=>sum+output.triangles.length/3,0),'print STL includes only the BOX and lid');
 let low=Infinity,high=-Infinity;
 for(let i=0;i<count;i++)for(let j=0;j<3;j++){
  const z=bytes.readFloatLE(84+i*50+12+j*12+8);low=Math.min(low,z);high=Math.max(high,z);
 }
 assert.ok(Math.abs(low)<1e-4,'print assembly rests on Z=0');
 assert.ok(high>22,'print assembly contains the raised lid');
 await page.locator('#file').setInputFiles({name:'saved.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(edited))});
 await page.waitForFunction(()=>document.getElementById('body-count').textContent==='3');
 await page.locator('#features .tree-row').last().locator('button.row-label').click();
 assert.equal(await page.locator('#cad-autoExpandMotion').isChecked(),true);
 assert.equal(await page.locator('#cad-snapLatch').isChecked(),true);
 assert.equal(await page.locator('#cad-motionGap').inputValue(),'0.8');
 assert.equal(await page.locator('#cad-latchGap').inputValue(),'0.5');
 assert.equal(await page.locator('#cad-seamGap').inputValue(),'0.5');
 assert.equal(await page.locator('#cad-latchEngagement').inputValue(),'0.2');
 await page.locator('#cad-cancel').click();
 assert.deepEqual(errors,[]);
 console.log('PASS optional motion expansion and snap latch preview, history edit, save/load, and print STL');
}finally{await browser.close();}
