import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {defaults} from '../src/geometry.js';

const browser=await chromium.launch({channel:'msedge',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1500,height:1100}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5188');
 await page.locator('#file').setInputFiles({name:'box.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({format:'forma-cad',version:1,features:[{...defaults,id:'b',name:'box',width:30,height:20,depth:10,x:20}]}))});
 await page.waitForFunction(()=>document.getElementById('body-count').textContent==='1');
 await page.locator('[data-view=top]').click();
 await page.locator('#fit').click();
 const rect=await page.locator('canvas').boundingBox(),cx=rect.x+rect.width/2,cy=rect.y+rect.height/2,host=page.locator('#canvas-host');
 const camera=async()=>JSON.parse(await host.getAttribute('data-camera-state'));
 const preview=async()=>JSON.parse(await host.getAttribute('data-move-preview'));
 await page.locator('#move-tool').click();
 await page.mouse.click(cx+30,cy+20);
 assert.equal(await host.getAttribute('data-move-active'),'true');
 await page.mouse.move(cx+75,cy);
 await page.mouse.down();
 await page.mouse.move(cx+115,cy,{steps:8});
 await page.mouse.up();
 await page.locator('#move-x').fill('0');
 await page.locator('[data-mode=rotate]').click();
 await page.mouse.move(cx+58,cy-58);
 await page.mouse.down();
 await page.mouse.move(cx+82,cy,{steps:12});
 const dragBody=await preview(),dragCamera=await camera();
 assert.ok(dragBody.rotation.some(angle=>Math.abs(angle)>.01),'rotation drag is active: '+JSON.stringify(dragBody));
 await page.keyboard.down('Shift');
 await page.mouse.wheel(0,-120);
 await page.keyboard.up('Shift');
 await page.waitForTimeout(100);
 const wheelCamera=await camera();
 assert.ok(wheelCamera.slice(0,7).some((n,i)=>Math.abs(n-dragCamera[i])>1e-6),'Shift+wheel rotates view during body drag');
 assert.equal(wheelCamera[7],dragCamera[7]);
 assert.deepEqual(await preview(),dragBody,'wheel alone leaves active drag angle intact');
 await page.mouse.move(cx+84,cy+2,{steps:2});
 const afterSmallMove=await preview(),angleStep=(a,b)=>Math.abs(Math.atan2(Math.sin(a-b),Math.cos(a-b)));
 assert.ok(afterSmallMove.rotation.every((angle,i)=>angleStep(angle,dragBody.rotation[i])<.6),'small pointer move after orbit should not make body angle jump: '+JSON.stringify({before:dragBody.rotation,after:afterSmallMove.rotation}));
 await page.mouse.up();
 const afterDragCamera=await camera(),afterDragBody=await preview();
 await page.keyboard.down('Shift');
 await page.mouse.wheel(0,120);
 await page.keyboard.up('Shift');
 await page.waitForTimeout(100);
 const afterRelease=await camera();
 assert.ok(afterRelease.slice(0,7).some((n,i)=>Math.abs(n-afterDragCamera[i])>1e-6),'Shift+wheel also rotates view after body drag');
 assert.equal(afterRelease[7],afterDragCamera[7]);
 assert.deepEqual(await preview(),afterDragBody,'view change after drag leaves body angle intact');
 assert.deepEqual(errors,[]);
 console.log('PASS Shift+wheel orbits view during move and active rotation drag without changing zoom or body angle');
}finally{await browser.close();}
