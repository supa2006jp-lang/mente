import assert from 'node:assert/strict';
import {printSupportExportCandidates,savedSupportExportGroups} from '../src/print-support-export-choice.js';
const wall=(id,target)=>({kind:'cadop',id,spec:{type:'printSupport',id,target,style:'walls'}});
const a=wall('support-a','body-a'),b=wall('support-b','body-b'),posts={kind:'cadop',id:'posts',spec:{type:'printSupport',style:'posts'}},operation={kind:'cadop',id:'move',spec:{type:'move'}};
assert.deepEqual(printSupportExportCandidates([posts,operation],['posts','move']),[]);
assert.deepEqual(printSupportExportCandidates([a],[]),[],'hidden or replaced supports do not trigger guidance');
assert.deepEqual(printSupportExportCandidates([a],['support-a']),[{feature:a,index:0,later:false}]);
assert.deepEqual(printSupportExportCandidates([a,posts,b,operation],['support-a','support-b','posts']),[{feature:a,index:0,later:true},{feature:b,index:2,later:true}]);
const visible=['support-a','support-b'];
const combined={ids:visible,index:0,all:true};
assert.deepEqual(savedSupportExportGroups([a,operation,b],visible),[combined]);
assert.deepEqual(savedSupportExportGroups([a,operation,b],['support-a']),[]);
assert.deepEqual(savedSupportExportGroups([a,{...b,analysis:{printSupport:{complete:false}}}],visible),[]);
const batch=feature=>({...feature,spec:{...feature.spec,batch:true,batchGroup:'batch'}});
assert.deepEqual(savedSupportExportGroups([batch(a),batch(b)],visible),[{ids:visible,index:0}]);
assert.deepEqual(savedSupportExportGroups([batch(a),operation,b],visible),[{ids:['support-a'],index:0},combined]);
console.log('PASS visible thin-wall targets, single and combined choices, original batches, and hidden/incomplete support exclusion');
