import {chromium} from 'playwright';
import * as THREE from 'three';
import * as R from 'replicad';
import init from '../node_modules/replicad-opencascadejs/dist/replicad_single.js';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {defaults} from '../src/geometry.js';
import {runOperation} from '../src/kernel.js';

R.setOC(await init({wasmBinary:await fs.readFile('node_modules/replicad-opencascadejs/dist/replicad_single.wasm')}));
const source={...defaults,id:'source',name:'対象',width:30,height:20,depth:20};
const spec={type:'enclose',id:'hinge',target:'source',thickness:2,clearance:.5,boxMode:true,faces:[],enclosureSplit:'XY',splitOffset:10,hinge:true,hingeEdge:'+Y',hingeRadialGap:.5,hingeAxialGap:.5,hingeAngle:0};
const operation=runOperation([source],spec),body=operation.outputs[0],vertices=[];
for(let i=0;i<body.vertices.length;i+=3)vertices.push(body.vertices.slice(i,i+3));
const barrel=vertices.filter(v=>v[1]>13&&Math.abs(v[2]-10)<5);
assert.ok(barrel.length>100,'barrel tessellation is present');
const capX=Math.max(...barrel.map(v=>v[0])),maxY=Math.max(...barrel.map(v=>v[1]));
const zRange=[Math.min(...barrel.map(v=>v[2])),Math.max(...barrel.map(v=>v[2]))];
const capOuterDiameter=zRange[1]-zRange[0],cap=[capX,maxY-capOuterDiameter/2,(zRange[0]+zRange[1])/2];
const circle={...defaults,kind:'sketch',id:'existing-circle',name:'ヒンジに合わせたい円',profile:'circle',plane:'XY',x:0,y:cap[1],z:cap[2],diameter:4,operation:'new',groupId:'circle-group',groupNumber:1};
const point={...defaults,kind:'sketch',id:'existing-point',name:'ヒンジに合わせたい点',profile:'point',plane:'XY',x:0,y:cap[1],z:cap[2],diameter:9,operation:'new',groupId:'point-group',groupNumber:2};
const browser=await chromium.launch({channel:'msedge',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1800,height:1100},acceptDownloads:true}),errors=[];
 page.setDefaultTimeout(30000);page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept(d.defaultValue()));
 await page.addInitScript(()=>Object.defineProperty(window,'showSaveFilePicker',{value:undefined,configurable:true}));
 await page.goto('http://127.0.0.1:5188');
 await page.locator('#file').setInputFiles({name:'existing-hinge-circle.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({format:'forma-cad',version:1,features:[source,{kind:'cadop',id:'enclosure',name:'囲み',spec,...operation},circle,point]}))});
 await page.waitForFunction(()=>document.getElementById('feature-count').textContent==='4');
 const project=async point=>{const rect=await page.locator('canvas').boundingBox(),state=JSON.parse(await page.locator('#canvas-host').getAttribute('data-camera-state'));const camera=new THREE.OrthographicCamera(-100*rect.width/rect.height,100*rect.width/rect.height,100,-100,.1,100000);camera.position.fromArray(state);camera.quaternion.fromArray(state,3);camera.zoom=state[7];camera.updateProjectionMatrix();camera.updateMatrixWorld(true);const p=new THREE.Vector3(...point).project(camera);return {x:rect.x+(p.x+1)*rect.width/2,y:rect.y+(1-p.y)*rect.height/2};};
 const distance=(a,b)=>Math.hypot(a.x-b.x,a.y-b.y);
 await page.locator('#features .tree-row').nth(2).locator('.row-label').click();
 await page.locator('[data-view=right]').click();await page.locator('#fit').click();
 const align=page.locator('#align-hinge-sketch');await align.waitFor({state:'visible'});await align.click();
 const capScreen=await project(cap);
 await page.waitForFunction(([x,y])=>[...document.querySelectorAll('#hinge-align-markers button')].some(el=>{const r=el.getBoundingClientRect();return !el.hidden&&Math.hypot(r.left+r.width/2-x,r.top+r.height/2-y)<3;}),[capScreen.x,capScreen.y]);
 await page.mouse.click(capScreen.x,capScreen.y);
 await page.waitForFunction(x=>Math.abs(Number(document.getElementById('x').value)-x)<.002,capX);
 const download=page.waitForEvent('download');await page.locator('#save').click();const data=JSON.parse(await fs.readFile(await(await download).path(),'utf8'));
 const corrected=data.features.find(f=>f.id===circle.id);assert.ok(corrected,'existing circle keeps its feature ID');
 assert.ok(Math.abs(corrected.x-capX)<.002,`corrected circle depth ${corrected.x} must equal end-face depth ${capX}`);
 assert.ok(Math.abs(corrected.y-cap[1])<.002&&Math.abs(corrected.z-cap[2])<.002,'corrected circle center lies on the hinge axis');
 assert.equal(corrected.plane,'YZ','circle rotates into the hinge end-face plane');
 await page.locator('[data-view=iso]').click();await page.locator('#fit').click();
 const actual=await project([corrected.x,corrected.y,corrected.z]),expected=await project(cap);
 assert.ok(distance(actual,expected)<3,'corrected sketch stays aligned with the visible hinge cap in oblique view');
 await page.locator('#features .tree-row').nth(3).locator('.row-label').click();
 await page.locator('[data-view=right]').click();await page.locator('#fit').click();
 await align.click();
 const pointCapScreen=await project(cap);
 await page.waitForFunction(([x,y])=>[...document.querySelectorAll('#hinge-align-markers button')].some(el=>{const r=el.getBoundingClientRect();return !el.hidden&&Math.hypot(r.left+r.width/2-x,r.top+r.height/2-y)<3;}),[pointCapScreen.x,pointCapScreen.y]);
 await page.mouse.click(pointCapScreen.x,pointCapScreen.y);
 await page.waitForFunction(x=>Math.abs(Number(document.getElementById('x').value)-x)<.002,capX);
 const pointDownload=page.waitForEvent('download');await page.locator('#save').click();
 const pointData=JSON.parse(await fs.readFile(await(await pointDownload).path(),'utf8'));
 const correctedPoint=pointData.features.find(f=>f.id===point.id);
 assert.ok(correctedPoint,'existing point keeps its feature ID');
 assert.ok(Math.abs(correctedPoint.x-capX)<.002&&Math.abs(correctedPoint.y-cap[1])<.002&&Math.abs(correctedPoint.z-cap[2])<.002,'point center moves to clicked cap');
 assert.equal(correctedPoint.diameter,point.diameter,'point keeps its unrelated diameter field');
 assert.equal(correctedPoint.plane,point.plane,'point retains its original sketch plane');
 assert.ok(Math.abs(corrected.diameter-capOuterDiameter)<.01,`circle diameter ${corrected.diameter} must match the physical outer cap diameter ${capOuterDiameter}`);
 assert.ok(Math.abs(pointData.features.find(f=>f.id===circle.id).diameter-capOuterDiameter)<.01,'corrected circle remains at cap diameter');
 assert.deepEqual(errors,[]);
 console.log('PASS existing circle matches clicked hinge cap center and outer circumference; point only moves center');
}finally{await browser.close();}
