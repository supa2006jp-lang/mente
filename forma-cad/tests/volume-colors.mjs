import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import * as R from 'replicad';
import * as THREE from 'three';
import init from '../node_modules/replicad-opencascadejs/dist/replicad_single.js';
import {strFromU8,unzipSync} from 'three/addons/libs/fflate.module.js';
import {runOperation} from '../src/kernel.js';
import {defaults,validateProject} from '../src/geometry.js';
import {setBodyColor} from '../src/body-appearance.js';
import {volumeColorRecords} from '../src/volume-colors.js';
import {createColor3mf} from '../src/color-3mf.js';
import {setVolumeDisplay,volumeDisplayMeshes} from '../src/volume-color-view.js';
import {sectionCap,sectionSegments} from '../src/section-view.js';
import {bodyPaint,facePaintReference,prepareBodyPaint} from '../src/body-face-paint.js';

R.setOC(await init({wasmBinary:await fs.readFile('node_modules/replicad-opencascadejs/dist/replicad_single.wasm')}));
const red='#cc2222',blue='#1144bb',green='#338811';
const box=(id,x,color)=>({...defaults,id,name:id,kind:'extrusion',width:10,height:10,depth:10,x,bodyColors:{[id]:color}});
const sources=[box('a',0,red),box('b',6,blue),box('c',16,green)];
const apply=(features,spec)=>[...features,{kind:'cadop',id:spec.id,name:spec.type,spec,...runOperation(features,spec)}];
const join=(features,other,id)=>apply(features,{type:'join',id,target:'a',other,combineMode:'結合',keepTools:'削除'});
const joined=join(sources,'b','join1');
const parts=volumeColorRecords(joined).get('a');
const shapeOf=part=>R.deserializeShape(part.brep).asShape3D();
const volume=shape=>Math.round(R.measureVolume(shape)*1e6)/1e6;
assert.deepEqual(parts.map(p=>p.color),[red,blue]);
const [a,b]=parts.map(shapeOf),overlap=a.intersect(b);
try{assert.deepEqual([volume(a),volume(b),volume(overlap)],[1000,600,0]);}
finally{a.delete();b.delete();overlap.delete();}
const file=JSON.parse(JSON.stringify({format:'forma-cad',version:1,features:joined}));
assert.deepEqual(volumeColorRecords(validateProject(file)).get('a').map(p=>p.color),[red,blue]);
const mesh=new THREE.Mesh(new THREE.BoxGeometry(),new THREE.MeshStandardMaterial());
setVolumeDisplay(mesh,parts);
assert.equal(mesh.material.visible,false);
const plane=new THREE.Plane(new THREE.Vector3(0,0,1),-5);
assert.deepEqual(volumeDisplayMeshes(mesh).map(part=>{
 const cap=sectionCap(sectionSegments(part.geometry,plane),plane),positions=cap.attributes.position;
 let area=0;for(let i=0;i<positions.count;i+=3)area+=new THREE.Triangle(...[0,1,2].map(j=>new THREE.Vector3().fromBufferAttribute(positions,i+j))).getArea();
 cap.dispose();return [part.userData.volumeColor,Math.round(area)];
}),[[red,100],[blue,60]]);
const joinedAgain=join(joined,'c','join2');
assert.deepEqual(volumeColorRecords(joinedAgain).get('a').map(p=>p.color),[red,blue,green]);
const moved=apply(joinedAgain,{type:'move',id:'move',target:'a',rotation:[0,0,90],x:5,y:3,z:0});
assert.deepEqual(volumeColorRecords(moved).get('a').map(p=>p.color),[red,blue,green]);
const split=apply(moved,{type:'split',id:'split',target:'a',plane:'XY',offset:5,keep:'both'});
for(const id of ['a','split'])assert.equal(volumeColorRecords(split).get(id).length,3);
const resized=apply(joined,{type:'resize',id:'resize',targets:['a'],factor:2});
assert.deepEqual(volumeColorRecords(resized).get('a').map(part=>{const shape=shapeOf(part);try{return volume(shape);}finally{shape.delete();}}),[8000,4800]);
const fused=joined.at(-1).outputs[0],surface=new THREE.BufferGeometry().setAttribute('position',new THREE.Float32BufferAttribute(fused.vertices,3));
surface.setIndex(fused.triangles);
const top=[];for(let i=0;i<surface.index.count;i+=3)if([0,1,2].every(j=>surface.attributes.position.getZ(surface.index.getX(i+j))===10))top.push({start:i,count:3});
mesh.geometry=prepareBodyPaint(surface,[{...facePaintReference(surface,top),color:green}]);
setVolumeDisplay(mesh,parts);
assert.deepEqual(volumeDisplayMeshes(mesh).map(part=>bodyPaint(part.geometry)?.colors),[[green],[green]]);
const recolored=setBodyColor(joined,'a','#ff9900');
assert.equal(volumeColorRecords(recolored).has('a'),false);
assert.equal(recolored[0].bodyColors.a,red);
assert.equal(volumeColorRecords(setBodyColor(recolored,'a',null)).get('a').length,2);
// A painted insert keeps its entire interior volume in an unpainted target.
const enclosed=join([{...box('a',0,red),bodyColors:undefined},{...box('b',0,blue),width:4,height:4,depth:4,z:3}],'b','enclosed');
const embedded=volumeColorRecords(enclosed).get('a');
assert.deepEqual(embedded.map(part=>part.color),[blue,'#a3a197']);
assert.deepEqual(embedded.map(part=>{const shape=shapeOf(part);try{return volume(shape);}finally{shape.delete();}}),[64,936]);
const interiorFile=await createColor3mf(embedded.map(part=>({...part,name:part.color,group:{id:'a',name:'Enclosed insert'}})));
if(process.argv[3])await fs.writeFile(process.argv[3],interiorFile.data);
const {data,colorCount}=await createColor3mf(parts.map((part,index)=>({...part,name:'Volume '+(index+1),group:{id:'a',name:'Joined solids'}})));
const files=unzipSync(data),model=strFromU8(files['3D/3dmodel.model']),config=strFromU8(files['Metadata/model_settings.config']);
assert.equal(colorCount,2);assert.match(model,/<components><component objectid="2"\/><component objectid="3"\/><\/components>/);
assert.match(config,/<part id="2"[^>]*>.*?key="extruder" value="1"/);
assert.match(config,/<part id="3"[^>]*>.*?key="extruder" value="2"/);
if(process.argv[2])await fs.writeFile(process.argv[2],data);
console.log('PASS joined and overlapping colors retain closed 3D volumes, section areas, save/reload, moves, splits and 3MF filaments');
